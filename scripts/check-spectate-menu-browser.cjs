const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {launchBrowser}=require('./browser.cjs');
(async()=>{
 const secret='spectate-menu-test-'.repeat(4),{revision,createWorld}=require('../verification/world.cjs');
 const game=require('../server.js').createServer();
 await new Promise(r=>game.listen(0,'127.0.0.1',r));
 const origin=`http://127.0.0.1:${game.address().port}`;
 const service=await require('../verification/server.cjs').createServer({secret,origins:[origin]});
 await new Promise(r=>service.listen(0,'127.0.0.1',r));
 const serviceURL=`http://127.0.0.1:${service.address().port}`;
 const board=await require('../verification/local-leaderboard.cjs').createLocalLeaderboard({secret,revision,origins:origin});
 await new Promise(r=>board.listen(0,'127.0.0.1',r));
 const boardURL=`http://127.0.0.1:${board.address().port}`;
 let browser;
 try{
  const account=await (await fetch(boardURL+'/api/verified/account',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({nickname:'Watcher',password:'spectator-password',create:true})})).json();
  assert(account.token);
  browser=await launchBrowser({headless:true});
  const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(account=>{
   localStorage.setItem('lpr-account',JSON.stringify(account));localStorage.setItem('lpr-chat-visible','true');
  },account);
  await page.route('**/verification/config.js*',route=>route.fulfill({contentType:'text/javascript',body:`window.LPRVerificationConfig=${JSON.stringify({service:serviceURL,leaderboard:boardURL})};`}));
  const ids=['a'.repeat(32),'b'.repeat(32)],{world}=createWorld();
  const recorder=new (require('../verification/replay.cjs').Recorder)(world,revision),frame=recorder.frame();
  let empty=false,offline=false,endedId=null;
  await page.route(serviceURL+'/spectate**',route=>{
   if(offline)return route.fulfill({status:503,json:{}});
   if(new URL(route.request().url()).pathname==='/spectate')return route.fulfill({json:{results:empty?[]:ids.map((id,i)=>({id,nickname:i?'Second Driver':'Live Driver'})).filter(r=>r.id!==endedId)}});
   if(endedId&&route.request().url().endsWith(endedId))return route.fulfill({status:410,json:{}});
   const second=route.request().url().endsWith(ids[1]),speed=second?20:10;
   return route.fulfill({json:{format:'lpr-live-v1',sceneRevision:revision,hz:120,nickname:second?'Second Driver':'Live Driver',lap:2,bestLapMs:500,lapStates:[{lap:1,startTick:0,bestLapMs:0},{lap:2,startTick:60,bestLapMs:500}],track:recorder.track,frames:[[...frame.slice(0,4),speed,0,frame[6]],[120,...frame.slice(1,4),speed,0,frame[6]]],inputs:[[0,1,0,0,false,false,true]]}});
  });
  await page.addInitScript(()=>localStorage.setItem('lpr-release-notes-seen','2026-10-27-major-update'));
  await page.goto(origin);
  await page.locator('#active-drivers-list a').first().waitFor();
  assert.equal(await page.locator('#active-drivers-list a').count(),2);
  assert(await page.locator('#chat-panel').isVisible());
  const initialURL=page.url();
  await page.evaluate(()=>{window.__originalTrack=document.querySelector('#track');window.__originalCockpit=document.querySelector('#cockpit');});
  await page.locator('#active-drivers-list a').first().click();
  await page.waitForFunction(()=>document.querySelector('#speed').textContent==='36',null,{polling:100});
  assert.equal(page.url(),initialURL,'Watching keeps the original page and chat alive');
  assert.match(await page.locator('#spectate-label').textContent(),/Seurataan pelaajaa Live Driver/);
  assert(await page.evaluate(()=>document.querySelector('#track')===window.__originalTrack&&document.querySelector('#cockpit')===window.__originalCockpit),'The exact game canvases remain in use');
  assert.equal(await page.locator('iframe').count(),0,'No separate replay rendering frame');
  const gameBox=await page.locator('#spectate-game').boundingBox(),sideBox=await page.locator('#spectate-sidebar').boundingBox();
  assert(sideBox.x>=gameBox.x+gameBox.width-1,'Active drivers stay in the right sidebar');
  assert.equal(await page.locator('#active-drivers-list a[aria-current="true"]').textContent(),'Live Driver');
  await page.locator('#active-drivers-list a').nth(1).click();
  await page.waitForFunction(()=>document.querySelector('#speed').textContent==='72',null,{polling:100});
  assert.match(await page.locator('#spectate-label').textContent(),/Second Driver/);
  assert.equal(await page.locator('#active-drivers-list a[aria-current="true"]').textContent(),'Second Driver');
  await page.waitForFunction(()=>document.querySelector('#lap-count').textContent==='2',null,{polling:100});
  assert.equal(await page.locator('#best-time').textContent(),'--:--.---','Spectating never replaces the official track record with the watched driver’s best lap');
  assert.match(await page.locator('#lap-time').textContent(),/^00:00\./,'Lap time follows the delayed lap boundary');
  await page.keyboard.press('w');
  assert(await page.evaluate(()=>window.LPRSpectator.active),'Driving keys do not leave spectator mode');
  assert(await page.locator('#chat-panel').isVisible());
  await page.locator('#chat-input').fill('Chat works while watching');
  await page.locator('#chat-input').press('Enter');
  await page.waitForFunction(()=>document.querySelector('#chat-messages').textContent.includes('Chat works while watching'),null,{timeout:10000,polling:100}).catch(async error=>{console.error(await page.evaluate(()=>({status:document.querySelector('#chat-status').textContent,identity:!!window.LPRLeaderboard?.chatIdentity,input:document.querySelector('#chat-input').value})),errors);throw error;});
  assert((await (await fetch(serviceURL+'/api/chat')).json()).messages.some(m=>m.nickname==='Watcher'&&m.text==='Chat works while watching'));
  const directory=path.join(__dirname,'../artifacts/spectate');fs.mkdirSync(directory,{recursive:true});
  await page.screenshot({path:path.join(directory,'watch-desktop.png')});
  offline=true;await page.waitForFunction(()=>document.querySelector('#spectate-connection').textContent.includes('katkesi'),null,{polling:100});
  offline=false;await page.waitForFunction(()=>document.querySelector('#spectate-connection').hidden,null,{polling:100});
  endedId=ids[1];await page.waitForFunction(()=>document.querySelector('#spectate-connection').textContent.includes('seuraavaa ajoa'),null,{polling:100});
  await page.locator('#active-drivers-list a').filter({hasText:'Live Driver'}).click();
  await page.waitForFunction(()=>document.querySelector('#speed').textContent==='36'&&document.querySelector('#spectate-connection').hidden,null,{polling:100});
  assert(await page.evaluate(()=>window.LPRSpectator.active),'An ended session can be replaced without leaving the view');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#chat-input').fill('Mobile chat works too');await page.locator('#chat-input').press('Enter');
  await page.waitForFunction(()=>document.querySelector('#chat-messages').textContent.includes('Mobile chat works too'),null,{polling:100});
  const rail=await page.locator('#chat-panel').boundingBox(),modal=await page.locator('#settings-dialog').boundingBox();
  assert(rail.y>=modal.y+modal.height-1,'Mobile chat and viewer do not overlap');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No horizontal overflow');
  await page.screenshot({path:path.join(directory,'watch-mobile.png')});
  await page.locator('#spectate-back').click();
  assert(await page.locator('#spectate-view').isHidden());
  assert.equal(await page.evaluate(()=>window.LPRSpectator.active),false);
  assert(await page.evaluate(()=>document.querySelector('#track')===window.__originalTrack),'Returning preserves the original game');
  assert((await page.locator('#chat-input').inputValue())==='');
  assert((await page.locator('#chat-messages').textContent()).includes('Mobile chat works too'));
  await page.screenshot({path:path.join(directory,'drivers-mobile.png')});
  const mobileList=await page.locator('#active-drivers-list a').first().boundingBox();
  assert(mobileList.y+mobileList.height<=rail.y,'Mobile driver names remain visible above chat');
  await page.setViewportSize({width:1280,height:900});
  await page.screenshot({path:path.join(directory,'drivers-desktop.png')});
  empty=true;await page.waitForFunction(()=>document.querySelector('#active-drivers-status').textContent.includes('Ei aktiivisia'),null,{polling:100});
  assert.equal(await page.locator('#active-drivers-list a').count(),0);
  offline=true;await page.waitForFunction(()=>document.querySelector('#active-drivers-status').textContent.includes('ei saatu'),null,{polling:100});
  offline=false;empty=false;await page.locator('#active-drivers-list a').first().waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: native game renderer/HUD, right sidebar, live driver switching, lap boundaries, persistent chat, mobile layout and return');
 }finally{
  if(browser)await browser.close();
  await service.sessions.close();
  for(const server of [game,service,board]){server.closeAllConnections();await new Promise(r=>server.close(r));}
 }
})().catch(e=>{console.error(e);process.exitCode=1;});
