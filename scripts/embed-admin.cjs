// Keep the Worker pasteable as one module while editing the dashboard as normal HTML.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const worker = path.join(root, 'cloudflare/worker.mjs');
const html = fs.readFileSync(path.join(root, 'cloudflare/admin.html'), 'utf8').replace(/\r\n/g, '\n');
let source = fs.readFileSync(worker, 'utf8');
if (!/^const ADMIN_HTML = .*;$/m.test(source)) throw Error('Missing embedded dashboard');
source=source.replace(/^const ADMIN_HTML = .*;$/m, () => 'const ADMIN_HTML = ' + JSON.stringify(html) + ';');
const securityFile=path.join(root,'cloudflare/lap-security.mjs');
const security=fs.readFileSync(securityFile,'utf8').replace(/^const LAP_POLICY = .*;$/m,
  'const LAP_POLICY = '+JSON.stringify(require('./lap-policy.cjs')())+';');
fs.writeFileSync(securityFile,security);
const block='// BEGIN LAP SECURITY\n'+security.trim()+'\n// END LAP SECURITY';
source=source.replace(/\/\/ BEGIN LAP SECURITY[\s\S]*?\/\/ END LAP SECURITY/,()=>block);
if(!source.includes('// BEGIN LAP SECURITY'))throw Error('Missing lap security marker');
fs.writeFileSync(worker,source);
const schemaFile=path.join(root,'cloudflare/schema.sql');
const schema=fs.readFileSync(schemaFile,'utf8').split('-- Lap security (generated by build:worker)')[0].trimEnd();
const statements=new Function(security+'\nreturn LAP_SECURITY_SCHEMA;')();
fs.writeFileSync(schemaFile,schema+'\n\n-- Lap security (generated by build:worker)\n'+statements.map(sql=>sql+';').join('\n')+'\n');
