// Build a single pasteable Cloudflare Worker for the verified leaderboard.
// Inlines verification/protocol.mjs and the current simulation revision so the
// Worker only needs the VERIFICATION_SECRET secret and the DB binding.
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
const { revision } = require('../verification/world.cjs');

const replays = read('cloudflare/replays.mjs').replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
const protocol = read('verification/protocol.mjs').replace(/^export /gm, '');
const namePolicy = read('verification/name-policy.mjs').replace(/^export /gm, '');
let worker = read('cloudflare/verified-worker.mjs');
const importLine = /^import \{[^}]*\} from '\.\.\/verification\/protocol\.mjs';\n/m;
if (!importLine.test(worker)) throw Error('verified-worker.mjs must import ../verification/protocol.mjs');
worker = worker.replace(importLine, '').replace(/^import .*name-policy\.mjs';\n/m,'').replace(/^import .*replays\.mjs';\n/m,'').replace(/^import .*chat-moderation\.mjs';\n/m,'').replace(/^import .*championship\.mjs';\n/m,'').replace(/^import .*guests\.mjs';\n/m,'');
const chatModerationCode=read('cloudflare/chat-moderation.mjs').replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
const guestCode=read('cloudflare/guests.mjs').replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
const championshipCode=read('cloudflare/championship.mjs').replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
if (!worker.includes("const BUILD_REVISION='';")) throw Error('verified-worker.mjs must define BUILD_REVISION');
worker = worker.replace("const BUILD_REVISION='';", `const BUILD_REVISION=${JSON.stringify(revision)};`);
worker = worker.replace(/^export const schema=/m, 'const schema=');

const output = path.join(root, 'cloudflare/verified-worker.bundle.mjs');
fs.writeFileSync(output, [
  '// GENERATED by npm run build:verified-worker — do not edit. Paste this whole file into the',
  '// Cloudflare Worker editor (lpr-verified), bind D1 as DB and set the VERIFICATION_SECRET secret.',
  `// Simulation revision ${revision} (rebuild and repaste whenever the physics changes).`,
  '// --- verification/protocol.mjs ---',
  protocol.trim(),
  '// --- verification/name-policy.mjs ---',
  namePolicy.trim(),
  guestCode.trim(),
  replays.trim(),
  chatModerationCode.trim(),
  championshipCode.trim(),
  '// --- cloudflare/verified-worker.mjs ---',
  worker.trim(),
  ''
].join('\n'));

(async () => {
  const bundle = await import(pathToFileURL(output).href);
  if (typeof bundle.default?.fetch !== 'function') throw Error('Bundle does not export a Worker');
  const response = await bundle.default.fetch(new Request('https://service.test/api/verified/leaderboard'), { DB: null, VERIFICATION_SECRET: 'x'.repeat(32) });
  if (response.status !== 503) throw Error('Bundle sanity check failed: ' + response.status);
  console.log(`Wrote ${path.relative(root, output)} for revision ${revision}`);
})().catch(error => { console.error(error.message); process.exitCode = 1; });
